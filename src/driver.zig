//! The zilc compile pipeline.
//!
//!   .zig  --zig build-obj--> LLVM IR --rewrite--> Fil-C dialect IR --+
//!                                                                    |--filc clang--> safe binary
//!   .c/.cpp/.o/.a -----------------------------------------------------+
//!
//! Nothing here patches Zig or LLVM: stock Zig emits the IR, `ir.zig` rewrites
//! two lines of it, and Fil-C's clang runs the GIMSO pass and links.
//! Background and limits: cmem/roadmap.md P2, cmem/known-issues.md KI-4…KI-6.

const std = @import("std");
// Through the module, not the file: importing "ir.zig" directly would put the
// same file in two modules, which Zig rejects.
const ir = @import("zilc").ir;
const ir_std = @import("zilc").stdpatch;

/// Who provides `main`.
///
/// Zig's own start code cannot run under Fil-C: it does
/// `@ptrFromInt(getauxval(AT_PHDR))` to find the program headers, and a pointer
/// forged from an integer carries no capability, so the first read of it traps
/// (KI-5). `.zig` therefore generates a C-ABI `main` that calls the user's
/// `main` directly, and Zig's `start.zig` never enters the build.
pub const Entry = enum { auto, c, zig };

/// Which runtime the program links.
///
///  * `.filc` — Fil-C's `libpizlo`, the runtime every gate run uses today.
///  * `.zig`  — zilc's own Zig runtime (P3), linked ahead of `libpizlo` so each
///    entry point it defines overrides Fil-C's and the rest fall through.
///    ⚠️ Reserved: it is refused until the runtime is ready for testing, so a
///    build can never claim the Zig runtime while silently linking Fil-C's.
pub const Runtime = enum { filc, zig };

pub const Options = struct {
    inputs: []const []const u8,
    output: []const u8,
    entry: Entry = .auto,
    /// Zig optimize mode. ⚠️ Debug needs zilc's patched Fil-C clang (KI-4).
    optimize: []const u8 = "ReleaseSafe",
    /// ⚠️ Fil-C's libc is musl; a gnu target fails to link on `*64` symbols (KI-6).
    target: []const u8 = "x86_64-linux-musl",
    /// Emit a linked executable, or stop at objects.
    emit: enum { exe, obj } = .exe,
    runtime: Runtime = .filc,
    zig: []const u8,
    filc: []const u8,
    keep_temps: bool = false,
    verbose: bool = false,
    /// Parallel parts for a big module's code generation: 0 = automatic (cores, at most
    /// `max_auto_jobs`), 1 = never split. See `filcCompile`.
    jobs: u32 = 0,
};

pub const Error = error{ ToolFailed, NoInputs, UnsupportedInput, RuntimeNotReady };

/// Debug's Fil-C step runs at `-O1` like every mode since 2026-10-01. From 2026-09-23 it ran at
/// `-O0`, because Debug IR segfaulted Fil-C's pass at `-O1` (KI-4). The cause is Fil-C's
/// `indirectbr` lowering, which breaks phis when a function has several `indirectbr`s (Zig emits
/// one per `continue :label`). zilc's patched Fil-C clang fixes it (`tools/filc/`). `-O0` was not
/// free: it left syscall pointer arguments without capabilities (KI-19) and made Fil-C's pass
/// several times slower (KI-22). With the prebuilt clang, Debug builds now fail on KI-4.
pub fn isDebug(optimize: []const u8) bool {
    return std.mem.eql(u8, optimize, "Debug");
}

/// The generated entry module. It is the root; the user's file is a module
/// named `user`, so Zig never pulls in `start.zig`.
const entry_shim =
    \\// Generated by zilc. Do not edit; edit src/driver.zig.
    \\//
    \\// Zig's start.zig cannot run under Fil-C: it forges a pointer from
    \\// getauxval(AT_PHDR) to read the program headers, and a pointer made from
    \\// an integer has no capability, so the first read traps. This shim gives
    \\// Fil-C's musl a plain C `main` to call instead.
    \\const std = @import("std");
    \\const user = @import("user");
    \\
    \\// Zig's default panic handler prints a stack trace by capturing the CPU
    \\// registers with inline asm (std.debug's getcontext), which can never carry
    \\// capabilities, so Fil-C rightly refuses it. The root module may replace the
    \\// handler, and this shim is the root, so panics report through Fil-C instead:
    \\// zerror prints the message and stops the program the same way a memory-safety
    \\// violation does, with Fil-C's own stack trace (KI-7, design-decisions.md
    \\// invariant 5).
    \\pub const panic = std.debug.FullPanic(zilcPanic);
    \\
    \\// std's page_allocator maps memory with mmap and passes the end of its previous
    \\// mapping as an address hint. Under Fil-C that hint is a pointer one past an
    \\// object's end, which Fil-C's mmap rightly rejects (cmem/zig-upstream-notes.md
    \\// Z-2). std lets the root module supply the page allocator, so pages come from
    \\// Fil-C's malloc instead: real GC objects with exact capabilities.
    \\pub const os = struct {
    \\    pub const heap = struct {
    \\        pub const page_allocator = std.heap.c_allocator;
    \\    };
    \\};
    \\
    \\// std.crypto.random's thread-local CSPRNG first probes for QEMU by calling
    \\// madvise with a deliberately invalid advice (0xffffffff), expecting EINVAL.
    \\// Fil-C's madvise stops the program on an unrecognized advice instead of
    \\// returning EINVAL (cmem/workarounds.md KI-20). std's official option makes
    \\// every fill a getrandom call, through Fil-C's checked libc (directly, or via
    \\// zilc_syscall when std picks the raw syscall): the kernel's
    \\// CSPRNG, fork-safe by construction, and the madvise path is never reached.
    \\pub const std_options: std.Options = .{ .crypto_always_getrandom = true };
    \\
    \\extern fn zerror(str: [*:0]const u8) void;
    \\
    \\fn zilcPanic(msg: []const u8, first_trace_addr: ?usize) noreturn {
    \\    _ = first_trace_addr;
    \\    var buf: [1024]u8 = undefined;
    \\    const text = std.fmt.bufPrintZ(&buf, "zig panic: {s}", .{msg}) catch "zig panic (message too long)";
    \\    zerror(text);
    \\    std.process.abort(); // zerror does not return; this only satisfies `noreturn`
    \\}
    \\
    \\export fn main(argc: c_int, argv: [*][*:0]u8) c_int {
    \\    std.os.argv = argv[0..@intCast(argc)];
    \\
    \\    const Ret = @typeInfo(@TypeOf(user.main)).@"fn".return_type.?;
    \\    switch (@typeInfo(Ret)) {
    \\        .void => {
    \\            user.main();
    \\            return 0;
    \\        },
    \\        .int => return user.main(),
    \\        .error_union => {
    \\            const payload = @typeInfo(Ret).error_union.payload;
    \\            if (user.main()) |value| {
    \\                return if (payload == void) 0 else value;
    \\            } else |err| {
    \\                std.debug.print("error: {s}\n", .{@errorName(err)});
    \\                return 1;
    \\            }
    \\        },
    \\        else => @compileError("zilc: main must return void, !void, u8 or !u8"),
    \\    }
    \\}
    \\
;

/// The helper that Zig's raw `syscall` asm is redirected to (ir.rewriteSyscalls,
/// KI-7). It is compiled by Fil-C, so it is checked code reaching the kernel only
/// through Fil-C's libc, which also tells the GC before blocking.
///
/// Every argument arrives as a pointer, so a real pointer (a futex word, a
/// timespec) keeps its capability. It returns the kernel's convention, -errno
/// on failure, because that is what the Zig code around the asm expects.
///
/// Fil-C's generic `syscall()` handles some numbers (gettid, futex) but rejects
/// others ("unsupported syscall: 230"), so those go to their libc function.
/// Measured 2026-09-30 by tools/p3/syscall-probe.c.
const syscall_helper_c =
    \\// Generated by zilc: raw system calls from Zig's std, routed through Fil-C's libc.
    \\#define _GNU_SOURCE
    \\#include <errno.h>
    \\#include <sys/syscall.h>
    \\#include <time.h>
    \\#include <unistd.h>
    \\
    \\long zilc_syscall(long n, void *a1, void *a2, void *a3, void *a4, void *a5, void *a6) {
    \\    long r;
    \\    switch (n) {
    \\    case SYS_clock_nanosleep: {
    \\        // Rejected by Fil-C's generic syscall(); libc's returns an errno value.
    \\        int e = clock_nanosleep((clockid_t)(long)a1, (int)(long)a2, a3, a4);
    \\        return e ? -e : 0;
    \\    }
    \\    case SYS_futex:
    \\        // Fil-C emulates futexes in user space; the word and timeout keep their capabilities.
    \\        r = syscall(SYS_futex, a1, (long)a2, (long)a3, a4, a5, (long)a6);
    \\        break;
    \\    default:
    \\        r = syscall(n, a1, a2, a3, a4, a5, a6);
    \\        break;
    \\    }
    \\    return r == -1 ? -errno : r;
    \\}
    \\
;


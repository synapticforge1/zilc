// Derives src/runtime/libpas_sources.zig from libpas's common.mk (`PASSRCS`) and the `*.S`
// files next to them, so build.zig compiles exactly the files upstream's Makefile compiles.
// Re-run when the pin moves (tools/lib/tool.ts FILC_SHA).
//
//   bun tools/runtime/import-libpas-sources.ts

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { FILC_SHA, FILC_VERSION, REPO, linuxOnly, must, requireFilcSrc, ZIG } from "../lib/tool.ts";

await linuxOnly(import.meta);

const src = await requireFilcSrc();
const mk = await readFile(`${src}/libpas/common.mk`, "utf8");

// PASSRCS = \ <tab>src/libpas/a.c \ ... <tab>src/libpas/z.c
const m = mk.match(/^PASSRCS = \\\n((?:.*\\\n)*.*)$/m);
if (!m) throw new Error("PASSRCS not found in common.mk");
const all = m[1].split("\n").map((l) => l.replace(/\\$/, "").trim()).filter((l) => l.length);
const generated = all.filter((f) => f.endsWith("filc_native_forwarders.c"));
const c = all.filter((f) => !f.endsWith("filc_native_forwarders.c"));

// PASASMSRCS = $(sort $(wildcard src/libpas/*.S))
const asm: string[] = [];
for (const e of await readdir(`${src}/libpas/src/libpas`, { withFileTypes: true })) if (e.isFile() && e.name.endsWith(".S")) asm.push(`src/libpas/${e.name}`);
asm.sort();

const z = (s: string) => JSON.stringify(s);
const list = (name: string, doc: string, items: string[]) =>
  [`/// ${doc}`, `pub const ${name} = [_][]const u8{`, ...items.map((f) => `    ${z(f)},`), "};", ""].join("\n");

const out = [
  // libpas's build recipe, as data (third_party/LICENSES.md `libpas-recipe`).
  "// SPDX-License-Identifier: BSD-2-Clause",
  "//",
  "// GENERATED by tools/runtime/import-libpas-sources.ts. Do not edit: re-run the tool.",
  `// Source: Fil-C ${FILC_VERSION} (${FILC_SHA}), libpas/common.mk \`PASSRCS\` and libpas/src/libpas/*.S.`,
  "// Paths are relative to <filc-src>/libpas.",
  "",
  list("c", `\`PASSRCS\` minus the generated file (${c.length} files).`, c),
  list("generated", "In `PASSRCS` but generated at build time by zilc-gen (not read from the tree).", generated),
  list("assembly", "`PASASMSRCS`.", asm),
].join("\n");

const dest = `${REPO}/src/runtime/libpas_sources.zig`;
await mkdir(`${REPO}/src/runtime`, { recursive: true });
await writeFile(dest, out);
await must([ZIG, "fmt", dest]);
console.log(`${dest}: ${c.length} C files + ${generated.length} generated + ${asm.length} assembly, from ${src}/libpas/common.mk`);
